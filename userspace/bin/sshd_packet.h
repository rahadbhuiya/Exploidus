#pragma once
#include <stdint.h>
#include "../libc/syscall.h"

/*
 * SSH binary packet protocol (RFC 4253 Section 6), unencrypted mode
 * only (no MAC, block size fixed at 8 per the RFC's own minimum) --
 * this is the framing used from right after the identification
 * string exchange (sshd.c) until SSH_MSG_NEWKEYS, and what
 * SSH_MSG_KEXINIT rides in.
 *
 * Once encryption is wired in (not yet), sending/receiving switches
 * to a cipher-aware packet path -- these functions cover the
 * pre-encryption phase, which is as far as sshd currently gets.
 */

#define SSH_PACKET_MAX 35000  /* generous, safely above real KEXINIT
                                 * sizes; also the working ceiling
                                 * chacha20poly1305.c's MAC_DATA_MAX
                                 * (40KB) and ed25519.c's
                                 * ED25519_SCRATCH_MAX assume other
                                 * SSH data will fit under */

/* Sends `payload_len` bytes from `payload` as one SSH binary packet
 * (length-prefixed, randomly padded per RFC 4253 Section 6, using
 * real getrandom() padding). Returns 1 on success, 0 on a send
 * failure (connection likely gone). */
int ssh_packet_send(cap_token_t cap, int fd, const uint8_t *payload,
                     uint32_t payload_len);

/*
 * Reads one SSH binary packet into `out` (caller-provided buffer of
 * at least SSH_PACKET_MAX bytes), stripping the length/padding
 * framing. Returns the payload length on success, or -1 on a read
 * failure / malformed packet (bad length field, connection closed
 * mid-packet, etc.) -- callers must treat -1 as "stop, don't trust
 * `out`'s contents."
 */
int32_t ssh_packet_recv(cap_token_t cap, int fd, uint8_t *out);

/*
 * ssh_kexinit_build -- fills `out` with a complete SSH_MSG_KEXINIT
 * payload (RFC 4253 Section 7.1) advertising this server's only
 * supported algorithm in each category (see sshd_packet.c for the
 * exact list: curve25519-sha256 / ssh-ed25519 /
 * chacha20-poly1305@openssh.com). Returns the payload length.
 * `cookie` must be 16 bytes of real randomness (RFC 4253: "The
 * cookie MUST be a random value generated by the sender" --
 * getrandom(), not a fixed or predictable value).
 */
uint32_t ssh_kexinit_build(uint8_t *out, const uint8_t cookie[16]);

/*
 * ssh_kexinit_check -- parses a peer's SSH_MSG_KEXINIT payload
 * (`data`, `len` bytes, starting at the SSH_MSG_KEXINIT byte itself)
 * and checks whether it offers each algorithm this server requires
 * (see the .c file for the exact set) somewhere in the matching
 * name-list. Logs what the peer offered in every category either
 * way. Returns 1 if every required algorithm is present in the
 * peer's corresponding list, 0 otherwise (or on a malformed
 * payload).
 */
int ssh_kexinit_check(const uint8_t *data, uint32_t len);